import pandas as pd
import sqlite3

print("--- MEMULAI PROSES ETL OTOMATIS ---")

# 1. SIMULASI KONEKSI DATABASE (Menggunakan SQLite in-memory untuk latihan)
conn = sqlite3.connect(':memory:')
cursor = conn.cursor()

# 2. BUAT TABEL OLTP & MASUKKAN DATA MENTAH
cursor.execute("CREATE TABLE oltp_transactions (trx_id INT, trx_date TEXT, customer_id INT, product_id INT, qty INT, price REAL, synced INT)")
cursor.execute("INSERT INTO oltp_transactions VALUES (1, '2026-06-01', 1, 1, 2, 5000000, 0)")
cursor.execute("INSERT INTO oltp_transactions VALUES (2, '2026-06-02', 2, 2, 1, 250000, 0)")

# 3. BUAT TABEL DWH (Star Schema)
cursor.execute("CREATE TABLE fact_sales (sale_id INT, time_id INT, product_id INT, customer_id INT, jumlah INT, pendapatan REAL)")
conn.commit()

# 4. EXTRACT: Ambil data OLTP yang belum disinkronkan (synced = 0)
query_extract = "SELECT * FROM oltp_transactions WHERE synced = 0"
df_extract = pd.read_sql(query_extract, conn)

if not df_extract.empty:
    print(f"Berhasil mengekstrak {len(df_extract)} baris data baru dari OLTP.")

    # 5. TRANSFORM: Hitung pendapatan (qty * price)
    df_extract['pendapatan'] = df_extract['qty'] * df_extract['price']
    df_load = df_extract[['trx_id', 'trx_id', 'product_id', 'customer_id', 'qty', 'pendapatan']]
    df_load.columns = ['sale_id', 'time_id', 'product_id', 'customer_id', 'jumlah', 'pendapatan']

    # 6. LOAD: Masukkan ke DWH (fact_sales)
    df_load.to_sql('fact_sales', conn, if_exists='append', index=False)

    # 7. UPDATE STATUS OLTP (Menandai data sudah disinkronkan)
    cursor.execute("UPDATE oltp_transactions SET synced = 1 WHERE synced = 0")
    conn.commit()
    print("Proses LOAD dan pembaruan status OLTP berhasil!")
else:
    print("Tidak ada data baru untuk disinkronkan.")

# Uji hasil akhir di DWH
print("\n--- ISI DATA DI DWH (fact_sales) ---")
df_dwh = pd.read_sql("SELECT * FROM fact_sales", conn)
print(df_dwh)